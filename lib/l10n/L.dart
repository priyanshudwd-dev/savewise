enum MsgType {
  budget70,
  budget80,
  budget90,
  over,
  goalRisk,
  daily,
  monthly,
  recurring,
  savedMore,
  goalDone,
  badge,
}

class L {
  final String lang;
  const L(this.lang);

  static L of(BuildContext c) => Localizations.of<L>(c, L) ?? const L('en');

  bool get hi => lang == 'hi';

  String t(String k) => (hi ? _hi : _en)[k] ?? k;

  String cat(String k) => t('cat_$k');
  String src(String k) => t('src_$k');

  String greeting(int hour) {
    if (hour < 12) return t('gMorning');
    if (hour < 17) return t('gAfternoon');
    return t('gEvening');
  }

  List<String> get months =>
      hi
          ? const [
              'जनवरी', 'फ़रवरी', 'मार्च', 'अप्रैल', 'मई', 'जून',
              'जुलाई', 'अगस्त', 'सितंबर', 'अक्टूबर', 'नवंबर', 'दिसंबर',
            ]
          : const [
              'January', 'February', 'March', 'April', 'May', 'June',
              'July', 'August', 'September', 'October', 'November', 'December',
            ];

  String monthName(int m) => months[(m - 1).clamp(0, 11)];

  String msg(MsgType type, String personality, Map<String, String> p) {
    final bank = hi ? _msgHi : _msgEn;
    var s = bank[type]?[personality] ?? bank[type]!['normal']!;
    p.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }
}

class LDelegate extends LocalizationsDelegate<L> {
  const LDelegate();

  @override
  bool isSupported(Locale locale) => true;

  @override
  Future<L> load(Locale locale) =>
      SynchronousFuture(L(locale.languageCode == 'hi' ? 'hi' : 'en'));

  @override
  bool shouldReload(covariant LocalizationsDelegate<L> old) => false;
}

